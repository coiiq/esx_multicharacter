function IsSupportedLocale(locale)
    return type(locale) == 'string' and Locales[locale] ~= nil
end

function TranslateLocale(locale, key, replacements)
    locale = IsSupportedLocale(locale) and locale or (IsSupportedLocale(Config.Locale) and Config.Locale or 'en')
    local fallback = Locales.en or {}
    local value = (Locales[locale] and Locales[locale][key]) or fallback[key] or key

    if type(replacements) == 'table' then
        for replacementKey, replacementValue in pairs(replacements) do
            value = value:gsub('%%{' .. tostring(replacementKey) .. '}', function()
                return tostring(replacementValue)
            end)
        end
    end

    return value
end
